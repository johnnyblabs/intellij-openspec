#!/usr/bin/env python3
"""Capture the fingerprints of the router skill's reference files each OpenSpec release generates.

From CLI 2.2 the `openspec` router skill carries files beside its SKILL.md (`references/*.md`). `openspec update`
rewrites or deletes them without saying whether you edited them, and upstream's RELEASED_GENERATED_FINGERPRINTS set
covers SKILL.md files only. So the plugin can tell an untouched reference from an edited one, this script asks each
release's own `expectedSkillFiles` (`dist/core/skill-installer.js`) for the router's files and fingerprints every
file other than SKILL.md with upstream's `fingerprintGeneratedContent` (`dist/core/shared/generated-fingerprint.js`),
which `ReleasedSkillFingerprints.fingerprint` ports. It writes:

    src/main/resources/openspec/router-reference-fingerprints.txt
        a header naming the releases, then one 16-hex fingerprint per line, sorted and unique

Packages are installed into the shared scratch cache (scripts/lib/openspec_capture.py), never run through `npx`.

Usage: scripts/capture-router-references.py 2.2.0 [later releases ...]
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts" / "lib"))
from openspec_capture import package  # noqa: E402

RESOURCE = REPO / "src/main/resources/openspec/router-reference-fingerprints.txt"

DUMP = r"""
const {pathToFileURL} = await import('node:url');
const installer = await import(pathToFileURL(process.argv[2]).href);
const fp = await import(pathToFileURL(process.argv[3]).href);
const files = installer.expectedSkillFiles(process.argv[4], ['router']).get('openspec');
if (!files) throw new Error('no router skill in this release');
const out = {};
for (const [file, text] of files) if (file !== 'SKILL.md') out[file] = fp.fingerprintGeneratedContent(text);
process.stdout.write(JSON.stringify(out));
"""


def main():
    versions = sys.argv[1:]
    if not versions:
        sys.exit("name the releases, e.g. 2.2.0")
    prints = set()
    for v in versions:
        dist = Path(package(v)) / "dist/core"
        with tempfile.TemporaryDirectory() as tmp:
            script = Path(tmp) / "dump.mjs"
            script.write_text(DUMP)
            out = subprocess.run(["node", str(script), str(dist / "skill-installer.js"),
                                  str(dist / "shared/generated-fingerprint.js"), v],
                                 capture_output=True, text=True, check=True)
        files = json.loads(out.stdout)
        if not files:
            sys.exit(f"{v}: the router has no reference files")
        print(f"{v}: {', '.join(sorted(files))}")
        prints.update(files.values())
    header = ("# Fingerprints of the router skill's reference files (references/*.md), as generated by CLI "
              + ", ".join(versions) + ".\n"
              "# Generated by scripts/capture-router-references.py. Do not edit.\n")
    RESOURCE.write_text(header + "\n".join(sorted(prints)) + "\n")
    print(f"{len(prints)} fingerprints -> {RESOURCE.relative_to(REPO)}")


if __name__ == "__main__":
    main()
